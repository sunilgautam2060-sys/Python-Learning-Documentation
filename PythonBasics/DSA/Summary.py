


#| Pattern             | Main purpose                                               |
#| ------------------- | ---------------------------------------------------------- |
#| **Basic Traversal** | Visit/process every element                                |
#| **Accumulator**     | Maintain a running result such as sum/count                |
#| **Two Pointers**    | Move two indices strategically to reduce searching         |
#| **Sliding Window**  | Maintain a **contiguous window** satisfying some condition |
#| **Kadane's**        | Find maximum/minimum **subarray sum**                      |
#| **Fast & Slow**     | Maintain two indices moving at different/controlled rates  |
#| **3-Sum / 4-Sum**   | Find combinations whose sum meets a target                 |
#| **Prefix Sum**      | Answer **range/subarray sum queries efficiently**          |
#| **Suffix Sum**      | Quickly obtain sum from an index toward the end            |
